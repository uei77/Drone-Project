"""Writes the firmware files for a trained and evaluated run:
  main/model_data.c, model_data.h, model_meta.h   the int8 model and its class list
  main/situations.c                                the situation table, from situations.json

usage: python export_c.py --run run_visdrone_v21_s1 [--fw <firmware main/ folder>]
       python export_c.py --situations-only         after changing thr / n_on / responses in
                                                    situations.json: rewrites situations.c only
"""
import argparse, datetime, json, os
from labels import load_situations

HERE = os.path.dirname(os.path.abspath(__file__))
RESP = dict(none="RESP_NONE", report="RESP_REPORT", hold_report="RESP_HOLD_REPORT",
            center_hold="RESP_CENTER_HOLD", center_land="RESP_CENTER_LAND", climb_hold="RESP_CLIMB_HOLD")

ap = argparse.ArgumentParser()
ap.add_argument("--run")
ap.add_argument("--fw", default=os.path.join(HERE, "..", "scripts", "camera_scripts", "esp32_camera_scripts", "main"))
ap.add_argument("--situations", default=None)
ap.add_argument("--situations-only", action="store_true")
a = ap.parse_args()
stamp = datetime.date.today().isoformat()
_, classes = load_situations(a.situations)


def write_situations():
    rows = []
    for c in classes:
        if c["response"] not in RESP:
            raise SystemExit(f"situations.json: unknown response '{c['response']}' ({sorted(RESP)})")
        if c["name"] == "normal":
            rows.append('    { "normal", { 1.00f, 1.00f, 0, 0, 0, 0, 0 }, RESP_NONE, 0, 0 },')
        else:
            rows.append(f'    {{ "{c["name"]}", {{ {c["thr"]:.2f}f, {c["thr_low"]:.2f}f, {c["n_on"]}, {c["m_off"]}, '
                        f'{c["priority"]}, {c["cooldown_ms"]}, {c["max_active_ms"]} }}, {RESP[c["response"]]}, '
                        f'{c["urgency"]}, {c["hold_ms"]} }},')
    with open(os.path.join(a.fw, "situations.c"), "w") as f:
        f.write(f"/* generated by training/export_c.py on {stamp} from training/situations.json - do not edit.\n"
                " * To change a threshold or a response: edit situations.json, then\n"
                " *   python export_c.py --situations-only\n"
                " * thr / n_on come from the tracker table that training/evaluate.py prints. */\n"
                '#include "situations.h"\n\n'
                "/*  name, { thr, thr_low, n_on, m_off, priority, cooldown_ms, max_active_ms }, response, urgency, hold_ms */\n"
                "const sit_def_t SITUATIONS[MODEL_NUM_CLASSES] = {\n" + "\n".join(rows) + "\n};\n"
                "/* app_main() checks at boot that every name matches MODEL_CLASS_NAMES in order. */\n")
    print("wrote situations.c:", [c["name"] for c in classes])


if a.situations_only:
    write_situations()
    raise SystemExit(0)
if not a.run:
    ap.error("--run is needed (or --situations-only)")

tfl = open(os.path.join(a.run, "model_int8.tflite"), "rb").read()
ev = json.load(open(os.path.join(a.run, "eval.json")))
NAMES, K, H = ev["classes"], len(ev["classes"]), ev["state_dim"]
synthetic = ev["source"].startswith("synth")
name = os.path.basename(os.path.normpath(ev["data"]))
hdr = f"/* generated by training/export_c.py on {stamp} from {os.path.basename(a.run)}/model_int8.tflite - do not edit */\n"

with open(os.path.join(a.fw, "model_data.h"), "w") as f:
    f.write(hdr + "#pragma once\n#include <stdint.h>\n\n"
            "extern const uint8_t g_model_data[];\nextern const unsigned int g_model_data_len;\n")

with open(os.path.join(a.fw, "model_data.c"), "w") as f:
    f.write(hdr + '#include "model_data.h"\n\n')
    f.write("/* flatbuffer must be 16-byte aligned for TFLite Micro */\n")
    f.write(f"const uint8_t g_model_data[{len(tfl)}] __attribute__((aligned(16))) = {{\n")
    for i in range(0, len(tfl), 16):
        f.write("  " + ", ".join(f"0x{b:02x}" for b in tfl[i:i + 16]) + ",\n")
    f.write("};\n")
    f.write(f"const unsigned int g_model_data_len = {len(tfl)};\n")

ops = ", ".join(f"{k} x{v}" for k, v in sorted(ev["ops"].items()))
names = ", ".join(f'"{n}"' for n in NAMES)
with open(os.path.join(a.fw, "model_meta.h"), "w") as f:
    f.write(hdr + "#pragma once\n\n")
    f.write(f"#define MODEL_VERSION        \"selector-{ev['variant']}-{name}-{stamp}\"\n")
    f.write(f"#define MODEL_NUM_CLASSES    {K}\n")
    f.write(f"#define MODEL_STATE_DIM      {H}\n")
    f.write(f"#define MODEL_IMG_CHANNELS   {ev['channels']}   /* current, previous{', thermal' if ev['channels'] == 3 else ''} */\n")
    f.write(f"#define MODEL_TEMPERATURE    {ev['temperature']:.2f}f   /* fitted on validation streams */\n")
    f.write(f"#define MODEL_CLASS_NAMES_INIT {{ {names} }}\n")
    f.write("static const char *const MODEL_CLASS_NAMES[MODEL_NUM_CLASSES] = MODEL_CLASS_NAMES_INIT;\n")
    f.write(f"/* {ev['n_ops']} ops: {ops} */\n")
    if synthetic:
        f.write("/* NOTE: weights come from SYNTHETIC data. They prove the pipeline and give real timing and\n"
                "   memory numbers on the board; they are not fit to fly. Retrain on real flight data. */\n")
    else:
        rec = ", ".join(f"{k} {v:.2f}" for k, v in ev["float_recall"].items() if v is not None)
        f.write(f"/* trained on {ev['source']}; test recall per frame: {rec} */\n")
print("wrote model:", len(tfl), "bytes, classes", NAMES)

if NAMES == [c["name"] for c in classes]:
    write_situations()
else:
    print("NOTE: the model's classes are not the ones in situations.json, so situations.c was NOT written.\n"
          "      Its rows must be", NAMES, "in this order (edit it by hand for a test model).")
